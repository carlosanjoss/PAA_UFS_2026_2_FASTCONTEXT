
"""Generate AV2 figures and comparative tables from benchmark summaries."""

from __future__ import annotations

import argparse
import csv
from collections import defaultdict
from pathlib import Path
from typing import Any

from matplotlib import pyplot as plt

plt.switch_backend("Agg")

PROJECT_ROOT = Path(__file__).resolve().parents[2]
DEFAULT_INPUT = PROJECT_ROOT / "experiments" / "av2" / "final" / "summary.csv"
DEFAULT_FIGURES = PROJECT_ROOT / "reports" / "figures" / "av2"
DEFAULT_TABLES = PROJECT_ROOT / "reports" / "tables" / "av2"

ALGORITHMS = ("naive", "kmp", "boyer-moore", "rabin-karp")

REQUIRED_COLUMNS = {
    "scenario_id",
    "pattern_id",
    "pattern_category",
    "scale",
    "corpus_fraction",
    "algorithm",
    "repetitions",
    "total_characters",
    "occurrences",
    "mean_time_ms",
    "std_time_ms",
    "mean_comparisons",
}


def load_summary(path: Path) -> list[dict[str, Any]]:
    """Read and validate the summary generated by run_benchmarks.py."""

    if not path.is_file():
        raise FileNotFoundError(f"Benchmark summary not found: {path}")

    with path.open(encoding="utf-8-sig", newline="") as handle:
        reader = csv.DictReader(handle)

        if (
            not reader.fieldnames
            or not REQUIRED_COLUMNS.issubset(reader.fieldnames)
        ):
            missing = REQUIRED_COLUMNS - set(reader.fieldnames or [])
            raise ValueError(
                f"Missing summary columns: {sorted(missing)}"
            )

        source_rows = list(reader)

    if not source_rows:
        raise ValueError("The benchmark summary has no observations.")

    rows: list[dict[str, Any]] = []
    observed: set[tuple[str, str]] = set()

    per_scenario: dict[
        str, list[dict[str, Any]]
    ] = defaultdict(list)

    for source in source_rows:
        row: dict[str, Any] = dict(source)

        row["corpus_fraction"] = float(
            source["corpus_fraction"]
        )
        row["mean_time_ms"] = float(source["mean_time_ms"])
        row["std_time_ms"] = float(source["std_time_ms"])
        row["mean_comparisons"] = float(
            source["mean_comparisons"]
        )
        row["occurrences"] = int(source["occurrences"])
        row["total_characters"] = int(
            source["total_characters"]
        )
        row["repetitions"] = int(source["repetitions"])

        key = (
            str(row["scenario_id"]),
            str(row["algorithm"]),
        )

        if key in observed:
            raise ValueError(
                f"Duplicate scenario/algorithm entry: {key}"
            )

        observed.add(key)

        if row["algorithm"] not in ALGORITHMS:
            raise ValueError(
                f"Unexpected algorithm: {row['algorithm']}"
            )

        if (
            row["mean_time_ms"] <= 0
            or row["std_time_ms"] < 0
            or row["total_characters"] <= 0
            or row["repetitions"] < 1
        ):
            raise ValueError(
                f"Invalid numerical measurement: {key}"
            )

        rows.append(row)

        per_scenario[
            str(row["scenario_id"])
        ].append(row)

    for scenario_id, group in per_scenario.items():
        names = {
            str(row["algorithm"])
            for row in group
        }

        if names != set(ALGORITHMS):
            raise ValueError(
                f"Scenario {scenario_id} is missing algorithms: "
                f"{sorted(set(ALGORITHMS) - names)}"
            )

        for field in (
            "occurrences",
            "total_characters",
            "pattern_id",
            "scale",
        ):
            if len({row[field] for row in group}) != 1:
                raise ValueError(
                    f"Inconsistent {field} in {scenario_id}"
                )

        if len({
            row["repetitions"] for row in group
        }) != 1:
            raise ValueError(
                f"Inconsistent repetitions in {scenario_id}"
            )

    return rows


def build_speedups(
    rows: list[dict[str, Any]],
) -> list[dict[str, Any]]:
    """Calculate mean-time speedups relative to Naive."""

    baselines = {
        str(row["scenario_id"]): float(row["mean_time_ms"])
        for row in rows
        if row["algorithm"] == "naive"
    }

    result: list[dict[str, Any]] = []

    for row in sorted(
        rows,
        key=lambda item: (
            item["scenario_id"],
            item["algorithm"],
        ),
    ):
        result.append(
            {
                "scenario_id": row["scenario_id"],
                "pattern_id": row["pattern_id"],
                "pattern_category": row["pattern_category"],
                "scale": row["scale"],
                "corpus_fraction": row["corpus_fraction"],
                "algorithm": row["algorithm"],
                "repetitions": row["repetitions"],
                "total_characters": row["total_characters"],
                "occurrences": row["occurrences"],
                "mean_time_ms": row["mean_time_ms"],
                "std_time_ms": row["std_time_ms"],
                "speedup_vs_naive": round(
                    baselines[str(row["scenario_id"])]
                    / float(row["mean_time_ms"]),
                    6,
                ),
            }
        )

    return result


def write_csv(
    path: Path,
    rows: list[dict[str, Any]],
) -> None:
    """Write derived results without changing benchmark inputs."""

    path.parent.mkdir(
        parents=True,
        exist_ok=True,
    )

    with path.open(
        "w",
        encoding="utf-8",
        newline="",
    ) as handle:
        writer = csv.DictWriter(
            handle,
            fieldnames=list(rows[0]),
        )

        writer.writeheader()
        writer.writerows(rows)


def plot_pattern_scaling(
    rows: list[dict[str, Any]],
    pattern_id: str,
    folder: Path,
) -> None:
    """Plot execution time against actual input size."""

    selected = [
        row for row in rows
        if row["pattern_id"] == pattern_id
    ]

    if not selected:
        raise ValueError(
            f"Pattern not found: {pattern_id}"
        )

    fig, ax = plt.subplots(figsize=(10, 6))

    for algorithm in ALGORITHMS:
        group = sorted(
            (
                row for row in selected
                if row["algorithm"] == algorithm
            ),
            key=lambda row: row["total_characters"],
        )

        ax.errorbar(
            [
                row["total_characters"]
                for row in group
            ],
            [
                row["mean_time_ms"]
                for row in group
            ],
            yerr=[
                row["std_time_ms"]
                for row in group
            ],
            marker="o",
            capsize=4,
            label=algorithm,
        )

    ax.set_title(
        f"AV2 — Tempo por tamanho de entrada ({pattern_id})"
    )
    ax.set_xlabel("Caracteres processados")
    ax.set_ylabel(
        "Tempo médio ± desvio-padrão (ms)"
    )

    ax.grid(axis="y", alpha=0.25)
    ax.legend()

    fig.tight_layout()
    fig.savefig(
        folder / "scaling_time.png",
        dpi=180,
    )
    plt.close(fig)


def plot_character_comparisons(
    rows: list[dict[str, Any]],
    pattern_id: str,
    folder: Path,
) -> None:
    """Plot directly counted character comparisons."""

    selected = [
        row for row in rows
        if row["pattern_id"] == pattern_id
    ]

    scales = sorted({
        float(row["corpus_fraction"])
        for row in selected
    })

    algorithms = (
        "naive",
        "kmp",
        "boyer-moore",
    )

    x = list(range(len(scales)))
    width = 0.25

    fig, ax = plt.subplots(figsize=(10, 6))

    for index, algorithm in enumerate(algorithms):
        values = [
            next(
                float(row["mean_comparisons"])
                for row in selected
                if row["algorithm"] == algorithm
                and float(
                    row["corpus_fraction"]
                ) == fraction
            )
            for fraction in scales
        ]

        ax.bar(
            [
                value + (index - 1) * width
                for value in x
            ],
            values,
            width=width,
            label=algorithm,
        )

    ax.set_xticks(
        x,
        [f"{fraction:.0%}" for fraction in scales],
    )

    ax.set_title(
        f"AV2 — Comparações diretas ({pattern_id})"
    )
    ax.set_xlabel("Fração do corpus")
    ax.set_ylabel(
        "Comparações entre caracteres"
    )

    ax.legend()
    ax.grid(axis="y", alpha=0.25)

    fig.text(
        0.5,
        0.01,
        "Rabin-Karp excluído: seu contador não inclui "
        "o custo do rolling hash.",
        ha="center",
        fontsize=9,
    )

    fig.tight_layout(
        rect=(0, 0.04, 1, 1)
    )

    fig.savefig(
        folder / "character_comparisons.png",
        dpi=180,
    )
    plt.close(fig)


def plot_full_scale_patterns(
    rows: list[dict[str, Any]],
    folder: Path,
) -> None:
    """Compare all patterns at the full reference scale."""

    selected = [
        row for row in rows
        if row["corpus_fraction"] == 1.0
    ]

    pattern_ids = sorted({
        str(row["pattern_id"])
        for row in selected
    })

    if not pattern_ids:
        raise ValueError(
            "No full-scale experiments found."
        )

    fig, ax = plt.subplots(figsize=(14, 7))

    width = 0.2
    x = list(range(len(pattern_ids)))

    for index, algorithm in enumerate(ALGORITHMS):
        values = [
            next(
                float(row["mean_time_ms"])
                for row in selected
                if row["pattern_id"] == pattern_id
                and row["algorithm"] == algorithm
            )
            for pattern_id in pattern_ids
        ]

        ax.bar(
            [
                value + (index - 1.5) * width
                for value in x
            ],
            values,
            width=width,
            label=algorithm,
        )

    label_by_pattern: dict[str, str] = {}

    for row in selected:
        marker = (
            " [synthetic]"
            if row["scale"] == "synthetic_microbenchmark"
            else ""
        )

        label_by_pattern[
            str(row["pattern_id"])
        ] = str(row["pattern_id"]) + marker

    ax.set_xticks(
        x,
        [label_by_pattern[key] for key in pattern_ids],
        rotation=35,
        ha="right",
    )

    ax.set_title(
        "AV2 — Tempo por padrão "
        "(escala de referência 100%)"
    )
    ax.set_ylabel(
        "Tempo médio (ms) — escala logarítmica"
    )

    ax.set_yscale("log")
    ax.legend()
    ax.grid(axis="y", alpha=0.25)

    fig.tight_layout()
    fig.savefig(
        folder / "full_scale_patterns.png",
        dpi=180,
    )
    plt.close(fig)


def write_analysis(
    path: Path,
    speedups: list[dict[str, Any]],
    pattern_id: str,
) -> None:
    """Produce a descriptive Markdown table for the report."""

    rows = [
        row for row in speedups
        if row["pattern_id"] == pattern_id
        and row["corpus_fraction"] == 1.0
    ]

    if not rows:
        raise ValueError(
            f"Missing full-scale pattern: {pattern_id}"
        )

    by_algorithm = {
        str(row["algorithm"]): row
        for row in rows
    }

    lines = [
        "# AV2 — Análise descritiva do benchmark",
        "",
        f"Padrão em destaque: `{pattern_id}`. "
        "Escala de referência: 100%.",
        "",
        "| Algoritmo | Tempo médio (ms) | "
        "Desvio-padrão (ms) | Speedup vs Naive |",
        "|---|---:|---:|---:|",
    ]

    for algorithm in ALGORITHMS:
        item = by_algorithm[algorithm]

        lines.append(
            f"| {algorithm} | "
            f"{item['mean_time_ms']:.3f} | "
            f"{item['std_time_ms']:.3f} | "
            f"{item['speedup_vs_naive']:.2f}x |"
        )

    lines += [
        "",
        "## Metodologia e limites",
        "",
        "- Os tempos são médias de execuções medidas, "
        "sem incluir o aquecimento.",
        "- Cada cenário compara algoritmos sobre "
        "os mesmos textos e padrões.",
        "- Os tempos incluem o custo de pré-processamento "
        "executado por busca.",
        "- A razão de médias é descritiva; "
        "não representa significância estatística.",
        "- Comparações de Rabin-Karp não contabilizam "
        "atualizações de hashes.",
        "- Casos sintéticos não representam a "
        "distribuição natural de textos FastAPI.",
        "- Os dados da AV1 de recuperação e geração "
        "não são comparáveis diretamente.",
        "- Os gráficos são derivados de summary.csv; "
        "os resultados originais permanecem intactos.",
        "",
    ]

    path.parent.mkdir(
        parents=True,
        exist_ok=True,
    )

    path.write_text(
        "\n".join(lines),
        encoding="utf-8",
    )


def main() -> int:
    parser = argparse.ArgumentParser(
        description=__doc__,
    )

    parser.add_argument(
        "--input",
        type=Path,
        default=DEFAULT_INPUT,
    )
    parser.add_argument(
        "--figures-dir",
        type=Path,
        default=DEFAULT_FIGURES,
    )
    parser.add_argument(
        "--tables-dir",
        type=Path,
        default=DEFAULT_TABLES,
    )
    parser.add_argument(
        "--pattern-id",
        default="P-OAUTH2",
    )

    args = parser.parse_args()

    try:
        rows = load_summary(args.input)
        speedups = build_speedups(rows)

        args.figures_dir.mkdir(
            parents=True,
            exist_ok=True,
        )
        args.tables_dir.mkdir(
            parents=True,
            exist_ok=True,
        )

        write_csv(
            args.tables_dir / "speedups.csv",
            speedups,
        )

        plot_pattern_scaling(
            rows,
            args.pattern_id,
            args.figures_dir,
        )

        plot_character_comparisons(
            rows,
            args.pattern_id,
            args.figures_dir,
        )

        plot_full_scale_patterns(
            rows,
            args.figures_dir,
        )

        write_analysis(
            args.tables_dir / "analysis.md",
            speedups,
            args.pattern_id,
        )

    except (
        OSError,
        ValueError,
        KeyError,
    ) as error:
        print(
            f"AV2 analysis failed: {error}"
        )
        return 1

    print(
        f"Validated benchmark summary: {len(rows)} rows"
    )
    print(f"Figures: {args.figures_dir}")
    print(f"Tables and report: {args.tables_dir}")

    return 0


if __name__ == "__main__":
    raise SystemExit(main())
